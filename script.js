const template = document.getElementById("template")
const daftarKartu = document.getElementById ("daftar-kartu")

if (daftarKartu && template) {
    dataBerita.forEach(({ id, judul, deskripsi, kategori, waktu, masuk, gambar, altGambar }) => {
    const templateClone = template.content.cloneNode(true);

    const card = templateClone.querySelector(".artikel-card");
    card.href = `detail-berita.html?id=${id}`;
    card.setAttribute("aria-label", `Baca artikel: ${judul}`);

    card.querySelector(".artikel-title").textContent = judul;
    card.querySelector(".artikel-desc").textContent = deskripsi;
    card.querySelector(".artikel-font").textContent = kategori;
    card.querySelector(".artikel-waktu-baca").textContent = waktu;
    card.querySelector(".artikel-link-text").textContent = masuk;
    card.querySelector(".foto").src = gambar;
    card.querySelector(".foto").alt = altGambar;

    daftarKartu.appendChild(card);
});
}

const detailBerita = document.getElementById("detail-berita");

if (detailBerita) {
    const parameter = new URLSearchParams(window.location.search);
    const idBerita = Number(parameter.get("id"));
    const berita = dataBerita.find((item) => item.id === idBerita);

    if (berita) {
        const gambarBerita = detailBerita.querySelector(".foto");
        const kategoriBerita = detailBerita.querySelector(".artikel-font");
        const waktuBerita = detailBerita.querySelector(".waktu-teks");
        const tanggalBerita = detailBerita.querySelector(".tanggal-teks");
        const isiBerita = detailBerita.querySelector(".isi-artikel");

        gambarBerita.src = berita.gambar;
        gambarBerita.alt = berita.altGambar;
        kategoriBerita.textContent = berita.kategori;
        waktuBerita.textContent = berita.waktu;
        tanggalBerita.textContent = berita.tanggal.replace(/^●\s*/, "");

        const judulBerita = document.createElement("h2");
        judulBerita.className = "berita-title";
        judulBerita.textContent = berita.judul;
        isiBerita.replaceChildren(judulBerita);

        const deskripsiBerita = document.createElement("p");
        deskripsiBerita.className = "berita-desc";
        deskripsiBerita.textContent = berita.isi;
        isiBerita.appendChild(deskripsiBerita);

        berita.isiLanjutan.forEach(({ judul, teks }) => {
            const subjudulBerita = document.createElement("h3");
            subjudulBerita.className = "sub-berita";
            subjudulBerita.textContent = judul;

            const paragrafBerita = document.createElement("p");
            paragrafBerita.className = "berita-desc";
            paragrafBerita.textContent = teks;

            isiBerita.append(subjudulBerita, paragrafBerita);
        });

        detailBerita.hidden = false;
    } else {
        const pesanTidakDitemukan = document.createElement("p");
        pesanTidakDitemukan.setAttribute("role", "alert");
        pesanTidakDitemukan.textContent =
            "Artikel tidak ditemukan. Silakan kembali ke semua artikel.";
        detailBerita.before(pesanTidakDitemukan);
    }
}
